// ignore_for_file: avoid_print
import 'dart:io';

void main() {
  final file = File('extracted_calendar_data.md');
  if (!file.existsSync()) {
    print('Error: extracted_calendar_data.md not found!');
    exit(1);
  }

  final lines = file.readAsLinesSync();
  final intervals = <String>[];

  int currentMonth = 0;
  final monthNames = {
    'januar': 1,
    'februar': 2,
    'marts': 3,
    'april': 4,
    'maj': 5,
    'juni': 6,
    'august': 8,
    'oktober': 10,
    'november': 11,
    'december': 12,
  };

  for (final line in lines) {
    final trimmed = line.trim();
    if (trimmed.startsWith('####')) {
      // Parse month
      final parts = trimmed
          .replaceAll('####', '')
          .trim()
          .toLowerCase()
          .split(' ');
      final monthName = parts[0];
      currentMonth = monthNames[monthName] ?? 0;
      continue;
    }

    if (!trimmed.startsWith('|') ||
        trimmed.contains('Date') ||
        trimmed.contains('---')) {
      continue;
    }

    final cells = trimmed.split('|').map((s) => s.trim()).toList();
    if (cells.length < 5) {
      continue; // | empty | Date | Time | Activity | empty |
    }

    final dateStr = cells[1];
    final timeStr = cells[2];
    final activity = cells[3];

    if (dateStr.isEmpty || timeStr.isEmpty || activity.isEmpty) {
      continue;
    }

    // Parse day: "1. Jan (To)" -> day = 1
    final dayMatch = RegExp(r'^(\d+)\.').firstMatch(dateStr);
    if (dayMatch == null) {
      continue;
    }
    final day = int.parse(dayMatch.group(1)!);

    // Parse time: "00:00 - 10:00"
    final timeParts = timeStr.split('-').map((s) => s.trim()).toList();
    if (timeParts.length != 2) continue;

    final startTimeParts = timeParts[0].split(':');
    final endTimeParts = timeParts[1].split(':');

    final startHour = int.parse(startTimeParts[0]);
    final startMin = int.parse(startTimeParts[1]);

    final endHour = int.parse(endTimeParts[0]);
    final endMin = int.parse(endTimeParts[1]);

    final startUtc =
        'DateTime.utc(2026, $currentMonth, $day, $startHour, $startMin)';
    final endUtc = endHour == 24
        ? 'DateTime.utc(2026, $currentMonth, $day).add(const Duration(days: 1))'
        : 'DateTime.utc(2026, $currentMonth, $day, $endHour, $endMin)';

    // Determine quality and isGrayDay
    String quality;
    bool isGray = false;

    final actLower = activity.toLowerCase();
    if (actLower.contains('unfavorable')) {
      quality = 'PlantQuality.none';
      isGray = true;
    } else if (actLower.contains('root') ||
        actLower.contains('leaf and root')) {
      quality = 'PlantQuality.root';
    } else if (actLower.contains('leaf')) {
      quality = 'PlantQuality.leaf';
    } else if (actLower.contains('flower') || actLower.contains('ag-flower')) {
      quality = 'PlantQuality.flower';
    } else if (actLower.contains('fruit')) {
      quality = 'PlantQuality.fruit';
    } else {
      quality = 'PlantQuality.none';
    }

    intervals.add('''  PrecomputedInterval(
    start: $startUtc,
    end: $endUtc,
    quality: $quality,
    isGrayDay: $isGray,
    message: ${isGray ? "'Unfavorable period.'" : "''"},
  )''');
  }

  final output = File('lib/src/data/precomputed_calendar.dart');
  output.writeAsStringSync(
    '''// Auto-generated by tool/parse_calendar.dart. Do not edit manually.
import '../ephemeris_service.dart';

class PrecomputedInterval {
  final DateTime start;
  final DateTime end;
  final PlantQuality quality;
  final bool isGrayDay;
  final String message;

  const PrecomputedInterval({
    required this.start,
    required this.end,
    required this.quality,
    required this.isGrayDay,
    required this.message,
  });
}

final List<PrecomputedInterval> precomputed2026Intervals = [
${intervals.join(',\n')}
];
''',
  );

  print(
    'Generated lib/src/data/precomputed_calendar.dart with ${intervals.length} intervals!',
  );
}
