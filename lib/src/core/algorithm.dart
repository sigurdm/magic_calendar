import 'dart:collection';

import '../services/ephemeris_service.dart'
    show AstronomiaEphemerisService, IsolateEphemerisService;
import 'dornach_boundaries.dart';
import 'models/models.dart';

final LinkedHashMap<Object, (CalendarInfo withPlanets, CalendarInfo noPlanets)>
_calendarInfoCache =
    LinkedHashMap<Object, (CalendarInfo withPlanets, CalendarInfo noPlanets)>();
const int _maxCalendarInfoCacheEntries = 2048;

/// Returns the observer location version counter when [ephemeris] is a
/// cacheable concrete service, or `null` when [ephemeris] is a custom/mock
/// implementation.
int? ephemerisLocationVersion(EphemerisService ephemeris) =>
    _ephemerisLocationVersion(ephemeris);

int? _ephemerisLocationVersion(EphemerisService ephemeris) {
  if (ephemeris is AstronomiaEphemerisService) {
    return ephemeris.observerLocationVersion;
  }
  if (ephemeris is IsolateEphemerisService) {
    return ephemeris.observerLocationVersion;
  }
  return null;
}

/// Checks for planetary Trine aspects (120 degrees apart) and returns special plant quality if present.
({PlantQuality quality, String message}) calculateTrineQuality(
  List<PlanetInfo> planets,
  List<ConstellationBoundary> boundaries,
) {
  if (planets.length < 2) {
    return (quality: PlantQuality.none, message: '');
  }

  for (int i = 0; i < planets.length; i++) {
    for (int j = i + 1; j < planets.length; j++) {
      final p1 = planets[i];
      final p2 = planets[j];

      final isMoonTrine = p1.name == 'Moon' || p2.name == 'Moon';
      if (!isMoonTrine) {
        continue;
      }

      final otherPlanet = p1.name == 'Moon' ? p2.name : p1.name;

      // In Maria Thun biodynamic calendars, special aspect days are generated by the Moon trining classical bodies
      const classicalBodies = {'Jupiter', 'Venus', 'Saturn', 'Sun'};
      if (!classicalBodies.contains(otherPlanet)) {
        continue;
      }

      final orb = otherPlanet == 'Jupiter' ? 4.8 : 2.5;

      double diff = (p1.longitude - p2.longitude).abs() % 360.0;
      if (diff > 180.0) {
        diff = 360.0 - diff;
      }

      if ((diff - 120.0).abs() <= orb) {
        final q1 = getQualityFromLongitude(p1.longitude, boundaries);
        final q2 = getQualityFromLongitude(p2.longitude, boundaries);

        PlantQuality aspectQuality = PlantQuality.none;

        // In Maria Thun biodynamics, Trigon aspects only create Special Elemental Days
        // when both celestial bodies are located in constellations of the same element (triplicity).
        if (q1 == q2 && q1 != PlantQuality.none) {
          aspectQuality = q1;
        }

        if (aspectQuality != PlantQuality.none) {
          final qualityName = aspectQuality.displayName;
          return (
            quality: aspectQuality,
            message:
                'Special $qualityName Day: Planetary Trine between ${p1.name} and ${p2.name}.',
          );
        }
      }
    }
  }

  return (quality: PlantQuality.none, message: '');
}

/// Calculates complete calendar information for a given [time] using [ephemeris].
CalendarInfo getCalendarInfo(
  DateTime time,
  EphemerisService ephemeris, {
  bool includePlanets = false,
  List<ConstellationBoundary> boundaries = dornachBoundaries,
  double latitude = DefaultLocations.dornachLatitude,
  double longitude = DefaultLocations.dornachLongitude,
}) {
  final locVersion = _ephemerisLocationVersion(ephemeris);
  Object? cacheKey;
  if (locVersion != null) {
    final boundariesKey =
        identical(boundaries, dornachBoundaries) ||
            identical(boundaries, customCalendarBoundaries)
        ? identityHashCode(boundaries)
        : Object.hashAll(boundaries);
    cacheKey = (
      identityHashCode(ephemeris),
      locVersion,
      time.toUtc().millisecondsSinceEpoch,
      time.isUtc,
      boundariesKey,
      (latitude * 10000).round(),
      (longitude * 10000).round(),
    );
    final cached = _calendarInfoCache.remove(cacheKey);
    if (cached != null) {
      // Re-insert to maintain LRU order.
      _calendarInfoCache[cacheKey] = cached;
      return includePlanets ? cached.$1 : cached.$2;
    }
  }

  DiurnalRhythmInfo? diurnalRhythm;
  try {
    final sunTimes = ephemeris.getSunriseSunset(time, latitude, longitude);
    final DateTime effectiveNoon;
    if (sunTimes.sunrise == null &&
        sunTimes.sunset == null &&
        sunTimes.noon.isAtSameMomentAs(time)) {
      final utcNoon = DateTime.utc(
        time.year,
        time.month,
        time.day,
        12,
      ).subtract(Duration(seconds: (longitude * 240).round()));
      effectiveNoon = time.isUtc ? utcNoon : utcNoon.toLocal();
    } else {
      effectiveNoon = sunTimes.noon;
    }
    diurnalRhythm = DiurnalRhythmInfo.fromSunTimes(
      time: time,
      sunrise: sunTimes.sunrise,
      sunset: sunTimes.sunset,
      solarNoon: effectiveNoon,
    );
  } catch (_) {
    final fallbackNoon = time.isUtc
        ? DateTime.utc(time.year, time.month, time.day, 12)
        : DateTime(time.year, time.month, time.day, 12);
    diurnalRhythm = DiurnalRhythmInfo.fromSunTimes(
      time: time,
      sunrise: fallbackNoon.subtract(const Duration(hours: 6)),
      sunset: fallbackNoon.add(const Duration(hours: 6)),
      solarNoon: fallbackNoon,
    );
  }

  double moonLongitude;
  try {
    moonLongitude = ephemeris.getMoonLongitude(time);
  } catch (e) {
    return CalendarInfo(
      quality: PlantQuality.none,
      isGrayDay: false,
      message: 'Error calculating planetary positions: $e',
      sapFlow: '',
      vitality: '',
      moonPhase: MoonPhaseInfo(
        illuminatedFraction: 0,
        isWaxing: false,
        phaseAngle: 0,
      ),
      planets: [],
      diurnalRhythm: diurnalRhythm,
      transitionEnvelope: TransitionEnvelope.none,
    );
  }

  final transitionEnvelope = TransitionEnvelope.fromLongitude(
    moonLongitude,
    boundaries,
  );

  final planets = ephemeris.getPlanets(time);
  final bool isNearNode = ephemeris.isNearNode(time);
  final bool isNearPerigee = ephemeris.isNearPerigee(time);
  final bool isNearApogee = ephemeris.isNearApogee(time);
  final bool isMoonSaturnOpp = ephemeris.isMoonSaturnOpposition(time);
  bool isEclipse = false;
  try {
    isEclipse = ephemeris.isNearEclipse(time);
  } catch (_) {}

  final bool isGrayDay = isNearNode || isNearPerigee;
  String message = '';

  if (isNearNode) {
    message = 'Gray Day: Near Lunar Node.';
  } else if (isNearPerigee) {
    message = 'Gray Day: Near Lunar Perigee (Pg).';
  } else if (isEclipse) {
    message = 'Eclipse Window: 24h Cosmic Rest Window. Sowing discouraged.';
  } else if (isNearApogee) {
    message = 'Apogee Window (Ag): High Light & Warmth Impulse.';
  } else if (isMoonSaturnOpp) {
    message =
        'Moon-Saturn Opposition (180°): Fungal Resistance & Strong Root Vigor.';
  }

  List<PlanetaryAspect> activeAspects = const [];
  try {
    activeAspects = ephemeris.getAspects(time);
  } catch (_) {}

  final dec1 = ephemeris.getMoonDeclination(time);
  final dec2 = ephemeris.getMoonDeclination(time.add(const Duration(hours: 1)));
  final isAscending = dec2 > dec1;
  final declinationPart = isAscending
      ? 'Ascending: Sap rises.'
      : 'Descending: Sap recedes.';

  final String diurnalPart;
  switch (diurnalRhythm.phase) {
    case DiurnalPhase.morningExhalation:
      diurnalPart = 'Morning Exhalation: Earth breathes out, optimal for foliar misting & above-ground harvest.';
      break;
    case DiurnalPhase.solarNoonStillness:
      diurnalPart =
          'Solar Noon Stillness: Transpiration pause, avoid disturbance.';
      break;
    case DiurnalPhase.eveningInhalation:
      diurnalPart = 'Evening Inhalation: Earth breathes in, optimal for seed sowing & soil spray.';
      break;
    case DiurnalPhase.nightRest:
      diurnalPart = 'Night Rest: Subterranean consolidation and plant rest.';
      break;
  }
  final sapFlow = '$declinationPart $diurnalPart';

  final moonPhase = ephemeris.getMoonPhase(time);
  String vitality = moonPhase.name;
  if (moonPhase.isWaxing) {
    vitality += ' (Increasing moisture/vitality)';
  } else {
    vitality += ' (Decreasing moisture; good for storage)';
  }

  final CalendarInfo withPlanetsInfo;
  final CalendarInfo noPlanetsInfo;

  if (isGrayDay) {
    withPlanetsInfo = CalendarInfo(
      quality: PlantQuality.none,
      isGrayDay: true,
      isSpecial: false,
      isApogee: isNearApogee,
      isMoonSaturnOpposition: isMoonSaturnOpp,
      isEclipse: isEclipse,
      activeAspects: activeAspects,
      message: message,
      sapFlow: sapFlow,
      isMoonAscending: isAscending,
      vitality: vitality,
      moonPhase: moonPhase,
      planets: planets,
      diurnalRhythm: diurnalRhythm,
      transitionEnvelope: transitionEnvelope,
    );
    noPlanetsInfo = CalendarInfo(
      quality: PlantQuality.none,
      isGrayDay: true,
      isSpecial: false,
      isApogee: isNearApogee,
      isMoonSaturnOpposition: isMoonSaturnOpp,
      isEclipse: isEclipse,
      activeAspects: activeAspects,
      message: message,
      sapFlow: sapFlow,
      isMoonAscending: isAscending,
      vitality: vitality,
      moonPhase: moonPhase,
      planets: const <PlanetInfo>[],
      diurnalRhythm: diurnalRhythm,
      transitionEnvelope: transitionEnvelope,
    );
  } else {
    final trineResult = calculateTrineQuality(planets, boundaries);
    final PlantQuality trineQuality = trineResult.quality;
    PlantQuality quality = PlantQuality.none;
    if (trineQuality == PlantQuality.none) {
      quality = getQualityFromLongitude(moonLongitude, boundaries);
    } else {
      quality = trineQuality;
      if (message.isEmpty) {
        message = trineResult.message;
      }
    }

    final isSpecial =
        trineQuality != PlantQuality.none || isMoonSaturnOpp || isNearApogee;

    withPlanetsInfo = CalendarInfo(
      quality: quality,
      isGrayDay: false,
      isSpecial: isSpecial,
      isApogee: isNearApogee,
      isMoonSaturnOpposition: isMoonSaturnOpp,
      isEclipse: isEclipse,
      activeAspects: activeAspects,
      message: message,
      sapFlow: sapFlow,
      isMoonAscending: isAscending,
      vitality: vitality,
      moonPhase: moonPhase,
      planets: planets,
      diurnalRhythm: diurnalRhythm,
      transitionEnvelope: transitionEnvelope,
    );
    noPlanetsInfo = CalendarInfo(
      quality: quality,
      isGrayDay: false,
      isSpecial: isSpecial,
      isApogee: isNearApogee,
      isMoonSaturnOpposition: isMoonSaturnOpp,
      isEclipse: isEclipse,
      activeAspects: activeAspects,
      message: message,
      sapFlow: sapFlow,
      isMoonAscending: isAscending,
      vitality: vitality,
      moonPhase: moonPhase,
      planets: const <PlanetInfo>[],
      diurnalRhythm: diurnalRhythm,
      transitionEnvelope: transitionEnvelope,
    );
  }

  if (cacheKey != null) {
    if (_calendarInfoCache.length >= _maxCalendarInfoCacheEntries) {
      _calendarInfoCache.remove(_calendarInfoCache.keys.first);
    }
    _calendarInfoCache[cacheKey] = (withPlanetsInfo, noPlanetsInfo);
  }

  return includePlanets ? withPlanetsInfo : noPlanetsInfo;
}
